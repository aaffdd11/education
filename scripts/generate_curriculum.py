def write_l1(subject, items):
    d = ROOT / "L1" / subject
    d.mkdir(parents=True, exist_ok=True)
    for uid, title, core_q, goals, duration, materials, prereq, notes in items:
        path = d / f"{uid}-{title}.md"
        goals_md = "\n".join(f"- {g}" for g in goals)
        mats_md = "\n".join(f"- {m}" for m in materials)
        text = f"""# L1 · {subject} {uid} · {title}

## 基本信息

| 项目 | 内容 |
|------|------|
| 学科 | {subject} |
| 编号 | {uid} |
| 对象 | 约 9 岁 / 三年级 |
| 建议时长 | {duration} |
| 先修 | {prereq} |
| 对应 L2 | `L2/{subject}/{uid}-{title}.md` |

## 核心问题

{core_q}

## 学习目标

{goals_md}

## 材料清单（概要）

{mats_md}

## 课堂结构建议

1. **导入（5–8 分钟）**：提出核心问题，收集孩子已有经验
2. **探究（20–25 分钟）**：动手实验 / 测量 / 分类
3. **整理（8–10 分钟）**：用自己的话总结
4. **验收（5 分钟）**：对照 L2「基础」验收标准

## 安全与注意事项

{notes}

## 层级索引

- L1（本文件）：单元骨架
- L2：基础 / 进阶 / 拓展知识细节
- L3：互动与视频（见 `L3/`，部分单元已有示范）
"""
        path.write_text(text, encoding="utf-8")


def render_level(level_name, data):
    kp = "\n".join(f"- **{k}**：{v}" for k, v in data["知识点"])
    acts = "\n".join(f"{i+1}. {a}" for i, a in enumerate(data["活动"]))
    wrong = "\n".join(f"- {w}" for w in data["误区"])
    ok = "\n".join(f"- {c}" for c in data["验收"])
    return f"""### {level_name}

#### 知识点
{kp}

#### 学习活动
{acts}

#### 常见误区
{wrong}

#### 验收标准
{ok}
"""


def write_l2(subject, l1_items, l2_map):
    d = ROOT / "L2" / subject
    d.mkdir(parents=True, exist_ok=True)
    for uid, title, core_q, goals, duration, materials, prereq, notes in l1_items:
        info = l2_map[uid]
        assert info["title"] == title, (uid, info["title"], title)
        text = f"""# L2 · {subject} {uid} · {title}

> 对应 L1：`L1/{subject}/{uid}-{title}.md`

## 单元知识主线

**核心问题**：{core_q}
**关键概念**：{info['concepts']}

本文件按难度分为 **基础 → 进阶 → 拓展**。建议依次达成验收标准。

---

{render_level("基础（观察与口语概念）", info["base"])}

---

{render_level("进阶（记录与简单推理）", info["mid"])}

---

{render_level("拓展（变量与解释）", info["high"])}

---

## 家长 / 老师提示

- 安全：{notes}
- 先修：{prereq}
- 记录：鼓励孩子把「看到的」和「想到的」分开写。
- 评价：以验收标准为准，不要求背定义原文。
- 衔接 L3：若需互动或视频，使用同一单元编号在 `L3/` 下扩展。
"""
        (d / f"{uid}-{title}.md").write_text(text, encoding="utf-8")


def main():
    write_l1("物理", physics_l1)
    write_l1("化学", chem_l1)
    write_l1("数学", math_l1)
    write_l2("物理", physics_l1, physics_l2)
    write_l2("化学", chem_l1, chem_l2)
    write_l2("数学", math_l1, math_l2)
    files = list((ROOT / "L1").rglob("*.md")) + list((ROOT / "L2").rglob("*.md"))
    print(f"wrote {len(files)} markdown files under L1/L2")


if __name__ == "__main__":
    main()
