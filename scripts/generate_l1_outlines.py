def main():
    (ROOT / "总览.md").write_text(render_overview(), encoding="utf-8")
    for subject, units in [("物理", PHYSICS), ("化学", CHEM), ("数学", MATH)]:
        d = ROOT / subject
        d.mkdir(parents=True, exist_ok=True)
        # remove old L1 unit files in subject dir
        for old in d.glob("U*.md"):
            old.unlink()
        for u in units:
            path = d / f"{u['id']}-{u['title']}.md"
            path.write_text(render_unit(subject, u), encoding="utf-8")
            print("wrote", path.relative_to(ROOT.parent))
    print("overview ok")


if __name__ == "__main__":
    main()
