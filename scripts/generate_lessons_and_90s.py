def write_script(u: dict):
    VIDEO_DIR.mkdir(parents=True, exist_ok=True)
    # replace old scripts for these units
    rows = []
    t = 0
    for i, (pic, vo, cap, sec) in enumerate(u["shots"], 1):
        rows.append(f"| {i} | {pic} | {vo} | {cap} | {sec}s |")
        t += sec
    full_vo = "".join(s[1] for s in u["shots"])
    path = VIDEO_DIR / f"{u['subject']}-{u['id']}-{u['title']}.md"
    text = f"""# 90 秒脚本 · {u['subject']} {u['id']} · {u['title']}

## 元信息

| 项目 | 内容 |
|------|------|
| 趣味标题 | {u['fun_title']} |
| 目标时长 | **约 90 秒**（本脚本合计 **{t} 秒**） |
| 形式 | 实拍桌面 + 少量字幕贴纸 |
| 对应课案 | `课案/{u['subject']}/{u['id']}-{u['title']}.md` |
| 对应 L1 | `L1/{u['subject']}/{u['id']}-{u['title']}.md` |

## 一句话目标

{u['one_line_goal']}

## 完整旁白（可直接录）

{full_vo}

## 分镜表

| 镜号 | 画面 | 旁白 | 字幕 | 时长 |
|------|------|------|------|------|
{chr(10).join(rows)}

**合计：{t} 秒**

## 片尾行动号召

{u['kid_mission']}

## 收尾金句（可定格 2 秒）

{u['close_line']}

## 拍摄备注

- 语速：中慢，关键词略停
- 画面：真实材料、明亮桌面；少炫光
- 安全：{u['safety']}
- 禁忌：恐吓音效、品尝实验液、无防护高温操作
"""
    path.write_text(text, encoding="utf-8")
    return path


def write_indexes():
    # 课案 index
    lines = ["# 课案总览（深化每一课）", "", "每课含：开场、核心演示、孩子主任务、追问、收尾金句。", "每课配套约 90 秒脚本，见 `L3/视频/`。", ""]
    scripts = ["# 90 秒脚本总览", "", "全部 24 课，目标时长约 90 秒。", ""]
    for subj in ["物理", "化学", "数学"]:
        lines.append(f"## {subj}")
        lines.append("")
        lines.append("| 编号 | 单元 | 趣味标题 | 课案 | 90秒脚本 |")
        lines.append("|------|------|----------|------|----------|")
        scripts.append(f"## {subj}")
        scripts.append("")
        scripts.append("| 编号 | 单元 | 时长 | 文件 |")
        scripts.append("|------|------|------|------|")
        for u in LESSONS:
            if u["subject"] != subj:
                continue
            lines.append(
                f"| {u['id']} | {u['title']} | {u['fun_title']} | "
                f"[课案]({subj}/{u['id']}-{u['title']}.md) | "
                f"[脚本](../L3/视频/{u['subject']}-{u['id']}-{u['title']}.md) |"
            )
            scripts.append(
                f"| {u['id']} | {u['title']} | {u['duration']}s | "
                f"[{u['subject']}-{u['id']}-{u['title']}.md]({u['subject']}-{u['id']}-{u['title']}.md) |"
            )
        lines.append("")
        scripts.append("")
    (LESSON_DIR / "总览.md").write_text("\n".join(lines), encoding="utf-8")
    (VIDEO_DIR / "总览.md").write_text("\n".join(scripts), encoding="utf-8")


def main():
    # clean old video md that we will regenerate (keep schema elsewhere)
    if VIDEO_DIR.exists():
        for p in VIDEO_DIR.glob("*.md"):
            p.unlink()
    LESSON_DIR.mkdir(parents=True, exist_ok=True)
    for u in LESSONS:
        write_lesson(u)
        write_script(u)
        print(u["subject"], u["id"], u["duration"], "s")
    write_indexes()
    print("lessons:", len(list(LESSON_DIR.rglob("U*.md"))))
    print("scripts:", len(list(VIDEO_DIR.glob("*-U*.md"))))


if __name__ == "__main__":
    main()
